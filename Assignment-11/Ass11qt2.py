# Program to merge two lists and sort them

list1 = [30, 10, 20]
list2 = [60, 40, 50]

# Merge two lists
merged_list = list1 + list2

# Sort the merged list
merged_list.sort()

print("First list =", list1)
print("Second list =", list2)
print("Merged and sorted list =", merged_list)